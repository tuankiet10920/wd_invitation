<script setup lang="ts">
import { useEditorStore } from '~~/stores/editor';
import BoxToolComponent from '../BoxToolComponent.vue';
import ToggleComponent from './ToggleComponent.vue';

const editor = useEditorStore();

const shadowH = ref(0);
const shadowV = ref(0);
const shadowBlur = ref(10);
const shadowSpread = ref(0);
const shadowColor = ref('#808080');
const hasShadow = ref(false);

const updateShadow = () => {
    if (!editor.selectedNode) return;

    if (!hasShadow.value) {
        editor.updateNodeStyle(editor.selectedNode.id, { boxShadow: 'none' });
        return;
    }

    const shadow = `${shadowH.value}px ${shadowV.value}px ${shadowBlur.value}px ${shadowSpread.value}px ${shadowColor.value}`;
    editor.updateNodeStyle(editor.selectedNode.id, { boxShadow: shadow });
};

// Parse existing shadow
watch(() => editor.selectedNode, (node) => {
    if (node && node.styles?.boxShadow && node.styles.boxShadow !== 'none') {
        const shadow = node.styles.boxShadow;
        hasShadow.value = true;

        // Simple regex to parse px values and color
        // Assuming format: h v blur spread color OR color h v blur spread
        // This is a basic parser and might need robustness for complex shadows
        // For now, we assume standard format generated by this tool
        const parts = shadow.match(/(-?\d+)px\s+(-?\d+)px\s+(\d+)px\s+(-?\d+)px\s+(#[\w\d]+|rgb\(.*?\)|rgba\(.*?\)|[a-z]+)/);

        if (parts) {
            shadowH.value = parseInt(parts[1]!);
            shadowV.value = parseInt(parts[2]!);
            shadowBlur.value = parseInt(parts[3]!);
            shadowSpread.value = parseInt(parts[4]!);
            shadowColor.value = parts[5]!;
        }
    } else {
        hasShadow.value = false;
        // Reset defaults if no shadow
        shadowH.value = 0;
        shadowV.value = 0;
        shadowBlur.value = 10;
        shadowSpread.value = 0;
        shadowColor.value = '#808080';
    }
}, { immediate: true });

watch([hasShadow, shadowH, shadowV, shadowBlur, shadowSpread, shadowColor], () => {
    updateShadow();
});

</script>
<template>
    <BoxToolComponent>
        <template #header>
            <div class="fw-bold fs-14">
                Đổ bóng
            </div>
        </template>
        <template #body>
            <div class="p-2">
                <div class="d-flex align-items-center justify-content-between mb-3">
                    <span class="fs-13 fw-bold">Đổ bóng</span>
                    <div class="m-0 min-h-auto">
                        <ToggleComponent v-model="hasShadow" />
                    </div>
                </div>

                <div v-if="hasShadow">
                    <div class="mb-3">
                        <div class="d-flex align-items-center justify-content-between mb-2">
                            <span class="fs-13">Horizontal Length</span>
                            <div class="d-flex align-items-center gap-1">
                                <input type="number" class="form-control form-control-sm text-center" v-model="shadowH"
                                    style="width: 50px;">
                                <span class="fs-13 text-secondary">px</span>
                            </div>
                        </div>
                        <input type="range" class="form-range custom-range" v-model="shadowH" min="-100" max="100">
                    </div>

                    <div class="mb-3">
                        <div class="d-flex align-items-center justify-content-between mb-2">
                            <span class="fs-13">Vertical Length</span>
                            <div class="d-flex align-items-center gap-1">
                                <input type="number" class="form-control form-control-sm text-center" v-model="shadowV"
                                    style="width: 50px;">
                                <span class="fs-13 text-secondary">px</span>
                            </div>
                        </div>
                        <input type="range" class="form-range custom-range" v-model="shadowV" min="-100" max="100">
                    </div>

                    <div class="mb-3">
                        <div class="d-flex align-items-center justify-content-between mb-2">
                            <span class="fs-13">Blur Radius</span>
                            <div class="d-flex align-items-center gap-1">
                                <input type="number" class="form-control form-control-sm text-center"
                                    v-model="shadowBlur" min="0" style="width: 50px;">
                                <span class="fs-13 text-secondary">px</span>
                            </div>
                        </div>
                        <input type="range" class="form-range custom-range" v-model="shadowBlur" min="0" max="100">
                    </div>

                    <div class="mb-3">
                        <div class="d-flex align-items-center justify-content-between mb-2">
                            <span class="fs-13">Spread Radius</span>
                            <div class="d-flex align-items-center gap-1">
                                <input type="number" class="form-control form-control-sm text-center"
                                    v-model="shadowSpread" style="width: 50px;">
                                <span class="fs-13 text-secondary">px</span>
                            </div>
                        </div>
                        <input type="range" class="form-range custom-range" v-model="shadowSpread" min="-50" max="50">
                    </div>

                    <div class="d-flex align-items-center justify-content-between">
                        <span class="fs-13">Shadow Color</span>
                        <input type="color" class="color-picker border rounded cursor-pointer p-0" v-model="shadowColor"
                            style="width: 32px; height: 20px; border-radius: 4px;">
                    </div>
                </div>
            </div>
        </template>
    </BoxToolComponent>
</template>
